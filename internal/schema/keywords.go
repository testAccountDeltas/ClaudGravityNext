package schema

import (
	"fmt"
	"strings"

	"github.com/tidwall/gjson"
	"github.com/tidwall/sjson"
)

// unsupportedConstraints lists JSON Schema keywords Gemini's protobuf
// Schema has no concept of at all — each one is extracted into a
// description hint (moveConstraintsToDescription) before
// removeUnsupportedKeywords deletes the keyword itself, so the
// constraint's information survives in a form the model can at least read,
// even though nothing downstream can enforce it structurally anymore.
var unsupportedConstraints = []string{
	"minLength", "maxLength", "exclusiveMinimum", "exclusiveMaximum",
	"minimum", "maximum", "multipleOf", // MCP tools with numeric validators commonly set these
	"pattern", "minItems", "maxItems", "minProperties", "maxProperties",
	"default", "example", "examples", // Claude rejects these in VALIDATED mode
	"prefixItems", "uniqueItems", "contains", "minContains", "maxContains",
	"dependencies", "dependentRequired", "dependentSchemas", "contentEncoding", "contentMediaType",
	"patternProperties",
	"propertyNames",
	"readOnly", "writeOnly", "deprecated",
	"unevaluatedProperties", "unevaluatedItems", "$comment",
	"if", "then", "else", "not", "strict", // GAP-R17-10: Strip strict keyword
}

// removeKeywords deletes every occurrence of keywords from jsonStr, except
// where the keyword's own name is a genuine property name
// (isPropertyDefinition).
func removeKeywords(jsonStr string, keywords []string) string {
	deletePaths := make([]string, 0)
	pathsByField := findPathsByFields(jsonStr, keywords)
	for _, key := range keywords {
		for _, p := range pathsByField[key] {
			if isPropertyDefinition(trimSuffix(p, "."+key)) {
				continue
			}
			deletePaths = append(deletePaths, p)
		}
	}
	sortByDepth(deletePaths)
	for _, p := range deletePaths {
		jsonStr, _ = sjson.Delete(jsonStr, p)
	}
	return jsonStr
}

// removeUnsupportedKeywords strips every keyword Gemini's protobuf parser
// rejects outright (schema-identification keywords like $ref/$id/$schema,
// OpenAPI annotation keywords like discriminator/xml/externalDocs, plus
// every entry in unsupportedConstraints — already extracted to a
// description hint by moveConstraintsToDescription earlier in the
// pipeline), and x-* vendor extension fields.
func removeUnsupportedKeywords(jsonStr string) string {
	keywords := append(unsupportedConstraints,
		"$schema", "$defs", "definitions", "components", "const", "$ref", "$id", "id", "additionalProperties",
		"enumTitles", "prefill", // Claude/OpenCode schema metadata fields unsupported by Gemini
		"additionalItems", "contentSchema", "$anchor", "$dynamicAnchor", "$dynamicRef", "$vocabulary",
		"discriminator", "xml", "externalDocs",
		"title", "allOf", "anyOf", "oneOf",
	)

	// "title" is commonly auto-generated by Pydantic/TypeBox-generated MCP
	// tool schemas as the parameter's actual human-readable description
	// (with no separate "description" at all) — copy it into "description"
	// first, whenever the latter is empty, before the delete pass below
	// discards it with no trace.
	for _, p := range findPaths(jsonStr, "title") {
		parentPath := trimSuffix(p, ".title")
		if isPropertyDefinition(parentPath) {
			continue
		}
		titleVal := gjson.Get(jsonStr, p).String()
		if titleVal == "" {
			continue
		}
		descPath := joinPath(parentPath, "description")
		if existing := gjson.Get(jsonStr, descPath).String(); existing == "" {
			jsonStr, _ = sjson.Set(jsonStr, descPath, titleVal)
		}
	}

	// GAP-TL-06: "format" used to be in unsupportedConstraints and
	// stripped unconditionally — but Gemini's protobuf Schema actually
	// accepts a specific OpenAPI 3.0 subset of format values
	// (date-time/date/int32/int64/float/double/byte), used for real
	// things like Structured Outputs date/64-bit-int generation. Only
	// strip a format value OUTSIDE that safe set.
	safeFormats := map[string]bool{
		"date-time": true, "date": true, "int32": true, "int64": true,
		"float": true, "double": true, "byte": true,
	}
	for _, p := range findPaths(jsonStr, "format") {
		parentPath := trimSuffix(p, ".format")
		if isPropertyDefinition(parentPath) {
			continue
		}
		fmtVal := gjson.Get(jsonStr, p).String()
		if !safeFormats[fmtVal] {
			if fmtVal != "" {
				jsonStr = appendHint(jsonStr, parentPath, "format: "+fmtVal)
			}
			jsonStr, _ = sjson.Delete(jsonStr, p)
		}
	}

	deletePaths := make([]string, 0)
	pathsByField := findPathsByFields(jsonStr, keywords)
	for _, key := range keywords {
		for _, p := range pathsByField[key] {
			if isPropertyDefinition(trimSuffix(p, "."+key)) {
				continue
			}
			deletePaths = append(deletePaths, p)
		}
	}
	sortByDepth(deletePaths)
	for _, p := range deletePaths {
		jsonStr, _ = sjson.Delete(jsonStr, p)
	}
	jsonStr = removeExtensionFields(jsonStr)
	return jsonStr
}

// removeExtensionFields removes all x-* extension fields from the JSON
// schema (e.g. x-google-enum-descriptions) that Google APIs don't
// recognize.
func removeExtensionFields(jsonStr string) string {
	var paths []string
	walkForExtensions(gjson.Parse(jsonStr), "", &paths)
	b := []byte(jsonStr)
	for _, p := range paths {
		b, _ = sjson.DeleteBytes(b, p)
	}
	return string(b)
}

// geminiAllowedSchemaKeys defines the strict OpenAPI 3.0 whitelist of keys
// accepted by Google Gemini's protobuf Schema (google.ai.generativelanguage.v1beta.Schema).
// Any key outside this set causes Protobuf unmarshaling errors or speccheck violations.
var geminiAllowedSchemaKeys = map[string]bool{
	"type": true, "description": true, "properties": true, "required": true,
	"items": true, "enum": true, "nullable": true, "format": true,
}

// stripKeysNotInAllowlist walks all Schema nodes (root, object properties, array items)
// and strips any keyword outside geminiAllowedSchemaKeys. If a property defines
// "markdownDescription" without a "description", it rescues it into "description".
func stripKeysNotInAllowlist(jsonStr string) string {
	var deletePaths []string
	var walk func(node gjson.Result, currentPath string)
	walk = func(node gjson.Result, currentPath string) {
		if !node.IsObject() {
			return
		}
		// Rescue markdownDescription: if description is missing or only contains title/constraints
		if md := node.Get("markdownDescription").String(); md != "" {
			descPath := joinPath(currentPath, "description")
			existingDesc := gjson.Get(jsonStr, descPath).String()
			if existingDesc == "" {
				jsonStr, _ = sjson.Set(jsonStr, descPath, md)
			} else if !strings.Contains(existingDesc, md) {
				jsonStr, _ = sjson.Set(jsonStr, descPath, md+"\n\n"+existingDesc)
			}
		}

		node.ForEach(func(k, v gjson.Result) bool {
			key := k.String()
			fieldPath := joinPath(currentPath, escapeGJSONPathKey(key))
			if !geminiAllowedSchemaKeys[key] {
				deletePaths = append(deletePaths, fieldPath)
				return true
			}
			if key == "properties" {
				if !v.IsObject() {
					deletePaths = append(deletePaths, fieldPath)
					return true
				}
				v.ForEach(func(propKey, propVal gjson.Result) bool {
					propPath := joinPath(fieldPath, escapeGJSONPathKey(propKey.String()))
					walk(propVal, propPath)
					return true
				})
			} else if key == "items" {
				if !v.IsObject() {
					jsonStr, _ = sjson.SetRaw(jsonStr, fieldPath, `{}`)
				} else {
					walk(v, fieldPath)
				}
			}
			return true
		})
	}

	walk(gjson.Parse(jsonStr), "")
	sortByDepth(deletePaths)
	for _, p := range deletePaths {
		jsonStr, _ = sjson.Delete(jsonStr, p)
	}
	return jsonStr
}

// moveConstraintsToDescription extracts every keyword in
// unsupportedConstraints into a description hint before
// removeUnsupportedKeywords deletes it outright — an object/array-valued
// constraint (dependentRequired, dependencies, dependentSchemas) uses its
// compact JSON form as the hint text, lossy but strictly better than total
// silence.
// isJSSafeIntegerBound reports the bounds Zod adds to every integer field
// (minimum/maximum = -/+9007199254740991, JavaScript's safe integer range).
// They say nothing the model needs and were appended to the description of
// every integer parameter as "(maximum: 9007199254740991)".
func isJSSafeIntegerBound(key string, val gjson.Result) bool {
	if key != "minimum" && key != "maximum" {
		return false
	}
	return val.Type == gjson.Number && (val.Num == 9007199254740991 || val.Num == -9007199254740991)
}

func moveConstraintsToDescription(jsonStr string) string {
	pathsByField := findPathsByFields(jsonStr, unsupportedConstraints)
	for _, key := range unsupportedConstraints {
		for _, p := range pathsByField[key] {
			val := gjson.Get(jsonStr, p)
			if !val.Exists() {
				continue
			}
			parentPath := trimSuffix(p, "."+key)
			if isPropertyDefinition(parentPath) {
				continue
			}
			if isJSSafeIntegerBound(key, val) {
				continue
			}
			if val.IsObject() || val.IsArray() {
				jsonStr = appendHint(jsonStr, parentPath, fmt.Sprintf("%s: %s", key, val.Raw))
				continue
			}
			jsonStr = appendHint(jsonStr, parentPath, fmt.Sprintf("%s: %s", key, val.String()))
		}
	}
	return jsonStr
}

// addAdditionalPropertiesHints degrades "additionalProperties" into a
// description hint before Phase 3 strips the keyword entirely: "false"
// becomes "No extra properties allowed"; a genuine schema value (a
// free-form dict's value type) contributes its own "description" as
// "Values: ...", the model's only remaining clue about what a free-form
// dict's values are supposed to look like.
func addAdditionalPropertiesHints(jsonStr string) string {
	for _, p := range findPaths(jsonStr, "additionalProperties") {
		parentPath := trimSuffix(p, ".additionalProperties")
		if isPropertyDefinition(parentPath) {
			continue
		}
		v := gjson.Get(jsonStr, p)
		if v.Type == gjson.False {
			jsonStr = appendHint(jsonStr, parentPath, "No extra properties allowed")
			continue
		}
		if desc := v.Get("description").String(); desc != "" {
			jsonStr = appendHint(jsonStr, parentPath, "Values: "+desc)
		}
	}
	return jsonStr
}
